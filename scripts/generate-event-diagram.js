import { execFileSync } from "node:child_process";
import {
	mkdirSync,
	readdirSync,
	readFileSync,
	statSync,
	writeFileSync,
} from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DOCS_DIR = join(ROOT, "docs");
const D2_PATH = join(DOCS_DIR, "event-flow.d2");
const SVG_PATH = join(DOCS_DIR, "event-flow.svg");

const HTTP_METHODS = "Get|Post|Put|Patch|Delete";

function read(path) {
	return readFileSync(path, "utf8");
}

function collectTsFiles(dir, files = []) {
	for (const entry of readdirSync(dir)) {
		const path = join(dir, entry);
		const stat = statSync(path);
		if (stat.isDirectory()) {
			if (entry === "node_modules" || entry === "dist") continue;
			collectTsFiles(path, files);
			continue;
		}
		if (entry.endsWith(".ts") && !entry.endsWith(".d.ts")) {
			files.push(path);
		}
	}
	return files;
}

function parseEvents(source) {
	const events = {};
	const groups = source.matchAll(/(\w+)\s*:\s*\{([^}]+)\}/g);
	for (const [, group, body] of groups) {
		for (const [, key, value] of body.matchAll(/(\w+)\s*:\s*"([^"]+)"/g)) {
			events[`${group}.${key}`] = value;
		}
	}
	return events;
}

function parseQueues(source) {
	const queues = {};
	for (const [, key, value] of source.matchAll(/(\w+)\s*:\s*"([^"]+)"/g)) {
		queues[key] = value;
	}
	return queues;
}

function resolveEvent(events, group, key) {
	return events[`${group}.${key}`] ?? `${group}_${key}`;
}

function resolveQueue(queues, group) {
	return queues[group] ?? `${group}_queue`;
}

function analyzeWorkspace(kind) {
	const parent = join(ROOT, kind);
	const packages = [];

	for (const name of readdirSync(parent).sort()) {
		const srcDir = join(parent, name, "src");
		try {
			if (!statSync(srcDir).isDirectory()) continue;
		} catch {
			continue;
		}

		const all = collectTsFiles(srcDir).map(read).join("\n");

		const listenMatch = all.match(
			/createMicroservice[\s\S]*?rmqOptions\(QUEUES\.(\w+)\)/,
		);
		const prefixMatch = all.match(/setGlobalPrefix\(\s*"([^"]+)"/);
		const httpRoutes = [
			...all.matchAll(
				new RegExp(`@(${HTTP_METHODS})\\(\\s*"([^"]*)"\\s*\\)`, "g"),
			),
		].map(([, method, route]) => {
			const prefix = prefixMatch?.[1];
			const path = [prefix, route].filter(Boolean).join("/");
			return `${method.toUpperCase()} /${path}`;
		});

		const consumes = [
			...all.matchAll(/@MessagePattern\(\s*EVENTS\.(\w+)\.(\w+)/g),
		].map(([, group, key]) => ({ group, key }));

		const publishes = [...all.matchAll(/\.emit\(\s*EVENTS\.(\w+)\.(\w+)/g)].map(
			([, group, key]) => ({ group, key }),
		);

		packages.push({
			kind,
			name,
			listenQueueGroup: listenMatch?.[1] ?? null,
			httpRoutes,
			consumes,
			publishes,
		});
	}

	return packages;
}

function toId(name) {
	return name.replace(/[^a-zA-Z0-9]/g, "_");
}

function escapeLabel(value) {
	return value.replaceAll('"', '\\"');
}

function buildDiagram(events, queues, packages) {
	const queueOrder = Object.keys(queues);
	const queueIndex = (group) => {
		const index = queueOrder.indexOf(group);
		return index === -1 ? Number.POSITIVE_INFINITY : index;
	};

	const apps = packages.filter((pkg) => pkg.kind === "apps");
	const services = packages
		.filter((pkg) => pkg.kind === "services")
		.sort(
			(left, right) =>
				queueIndex(left.listenQueueGroup) - queueIndex(right.listenQueueGroup),
		);
	const usedQueueGroups = new Set();

	for (const pkg of packages) {
		if (pkg.listenQueueGroup) usedQueueGroups.add(pkg.listenQueueGroup);
		for (const event of [...pkg.consumes, ...pkg.publishes]) {
			usedQueueGroups.add(event.group);
		}
	}

	const lines = [
		"# Generated by scripts/generate-event-diagram.js — do not edit by hand",
		"# Run: pnpm diagram",
		"",
		"vars: {",
		"  d2-config: {",
		"    layout-engine: elk",
		"    theme-id: 300",
		"  }",
		"}",
		"",
		"direction: right",
		"",
		"classes: {",
		"  animated: {",
		"    style: {",
		"      animated: true",
		"    }",
		"  }",
		"}",
		"",
		"client: {",
		"  shape: person",
		"  label: Client",
		"}",
		"",
		"apps: Apps {",
	];

	for (const app of apps) {
		const id = toId(app.name);
		lines.push(`  ${id}: ${app.name} {`);
		lines.push("    shape: hexagon");
		if (app.httpRoutes.length > 0) {
			lines.push(`    tooltip: ${JSON.stringify(app.httpRoutes.join("\n"))}`);
		}
		lines.push("  }");
	}

	lines.push("}", "", "queues: RabbitMQ {");

	for (const group of queueOrder.filter((key) => usedQueueGroups.has(key))) {
		const queue = resolveQueue(queues, group);
		lines.push(`  ${toId(queue)}: ${queue} {`);
		lines.push("    shape: queue");
		lines.push("  }");
	}

	lines.push("}", "", "services: Services {");

	for (const service of services) {
		const id = toId(service.name);
		lines.push(`  ${id}: ${service.name} {`);
		lines.push("    shape: hexagon");
		lines.push("  }");
	}

	lines.push("}", "");

	const pushEdge = (from, to, label) => {
		lines.push(`${from} -> ${to}: {`);
		if (label) {
			lines.push(`  label: "${escapeLabel(label)}"`);
		}
		lines.push("  class: [animated]");
		lines.push("}");
	};

	for (const app of apps) {
		const appId = `apps.${toId(app.name)}`;
		for (const route of app.httpRoutes) {
			pushEdge("client", appId, route);
		}
		for (const event of app.publishes) {
			const eventName = resolveEvent(events, event.group, event.key);
			const queue = resolveQueue(queues, event.group);
			pushEdge(appId, `queues.${toId(queue)}`, eventName);
		}
	}

	for (const service of services) {
		const serviceId = `services.${toId(service.name)}`;
		if (service.listenQueueGroup) {
			const queue = resolveQueue(queues, service.listenQueueGroup);
			pushEdge(`queues.${toId(queue)}`, serviceId);
		}
		for (const event of service.publishes) {
			const eventName = resolveEvent(events, event.group, event.key);
			const queue = resolveQueue(queues, event.group);
			pushEdge(serviceId, `queues.${toId(queue)}`, eventName);
		}
	}

	lines.push("");
	return `${lines.join("\n")}\n`;
}

function main() {
	const events = parseEvents(read(join(ROOT, "packages/rabbitmq/src/events.ts")));
	const queues = parseQueues(read(join(ROOT, "packages/rabbitmq/src/queues.ts")));
	const packages = [...analyzeWorkspace("apps"), ...analyzeWorkspace("services")];
	const diagram = buildDiagram(events, queues, packages);

	mkdirSync(DOCS_DIR, { recursive: true });
	writeFileSync(D2_PATH, diagram);

	const publishers = packages.flatMap((pkg) =>
		pkg.publishes.map(
			(event) =>
				`${pkg.name} --${resolveEvent(events, event.group, event.key)}--> ${resolveQueue(queues, event.group)}`,
		),
	);
	const consumers = packages.flatMap((pkg) =>
		pkg.consumes.map(
			(event) =>
				`${resolveQueue(queues, event.group)} --${resolveEvent(events, event.group, event.key)}--> ${pkg.name}`,
		),
	);

	console.log(`Wrote ${relative(ROOT, D2_PATH)}`);
	for (const edge of [...publishers, ...consumers]) {
		console.log(`  ${edge}`);
	}

	try {
		execFileSync("d2", [D2_PATH, SVG_PATH], { stdio: "inherit" });
		console.log(`Wrote ${relative(ROOT, SVG_PATH)}`);
	} catch (error) {
		if (error.code === "ENOENT") {
			console.warn("d2 CLI not found. Install with: brew install d2");
			console.warn(`Diagram source is ready at ${relative(ROOT, D2_PATH)}`);
			return;
		}
		throw error;
	}
}

main();
